file_path = 'lib/shared/l10n/app_localizations.dart'
with open(file_path, 'r', encoding='utf-8') as f:
    code = f.read()

# For each language, find its block and append the missing keys before the closing bracket
for lang, kvs in translations.items():
    # Find block: 'es': { ... \n    },
    pattern = rf"('{lang}':\s*\{{.*?)(\n\s*\}},)"
    match = re.search(pattern, code, re.DOTALL)
    if not match:
        print(f"Error: Could not find block for {lang}")
        continue
    
    header_and_body = match.group(1)
    closing = match.group(2)
    
    # Generate Dart map entries
    new_entries = []
    for k, v in sorted(kvs.items()):
        # Escape any single quotes in value
        escaped_v = v.replace("\\'", "'").replace("'", "\\'")
        new_entries.append(f"      '{k}': '{escaped_v}',")
    
    replacement = header_and_body + "\n" + "\n".join(new_entries) + closing
    code = code[:match.start()] + replacement + code[match.end():]
    print(f"Injected {len(new_entries)} keys into '{lang}'")

with open(file_path, 'w', encoding='utf-8') as f:
    f.write(code)

